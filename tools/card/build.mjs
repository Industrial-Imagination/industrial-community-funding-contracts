import { execFileSync } from "node:child_process";
import fs from "node:fs";
import { gzipSync, gunzipSync } from "node:zlib";
import { createHash } from "node:crypto";
import sharp from "sharp";
import { keccak256 } from "ethers";
import assert from "node:assert/strict";
const read = (p) => fs.readFileSync(p);
const three = read("media/vendor/three-r162.txt");
const decoded = gunzipSync(Buffer.from(three.toString(), "base64"));
assert.equal(
  createHash("sha256").update(decoded).digest("hex"),
  "ecd9f6b9bc1a12efdf14d13e4c610c012903c141a77d967d3f500bc727f0896c",
);
assert(decoded.includes('const t="162"'));
const { data, info } = await sharp("media/vendor/logo-source.png")
  .removeAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });
const mask = Buffer.alloc(info.width * info.height);
let xmin = info.width,
  ymin = info.height,
  xmax = 0,
  ymax = 0;
for (let i = 0; i < mask.length; i++) {
  const [r, g, b] = data.subarray(i * 3, i * 3 + 3);
  mask[i] = Math.min(255, Math.max(0, Math.round(((g - 18) * 255) / 208)));
  if (r > g + 40) mask[i] = 110;
  if (mask[i] < 135) {
    const x = i % info.width,
      y = Math.floor(i / info.width);
    xmin = Math.min(x, xmin);
    ymin = Math.min(y, ymin);
    xmax = Math.max(x, xmax);
    ymax = Math.max(y, ymax);
  }
}
const logo = await sharp(mask, {
  raw: { width: info.width, height: info.height, channels: 1 },
})
  .extract({
    left: xmin,
    top: ymin,
    width: xmax - xmin + 1,
    height: ymax - ymin + 1,
  })
  .resize(900)
  .png({ palette: true, colours: 32 })
  .toBuffer();
const fontDir = "node_modules/@fontsource/ibm-plex-mono/";
const font = read(fontDir + "files/ibm-plex-mono-latin-500-normal.woff2");
fs.copyFileSync(fontDir + "LICENSE", "media/vendor/Plex-OFL.txt");
const source =
  "/* " +
  [
    "media/vendor/Three-MIT.txt",
    "media/vendor/IBM-OFL.txt",
    "media/vendor/Plex-OFL.txt",
  ]
    .map((p) => read(p).toString())
    .join("\n")
    .replaceAll("*/", "* /") +
  " */\n" +
  read("media/card.mjs")
    .toString()
    .replace("__LOGO__", "data:image/png;base64," + logo.toString("base64"))
    .replace("__FONT__", "data:font/woff2;base64," + font.toString("base64"));
const compressed = gzipSync(source, { level: 9 });
compressed[9] = 255;
const card = Buffer.from(compressed.toString("base64"));
fs.writeFileSync("media/dist/runtime.txt", card);
const template = read("media/player.html").toString();
const parts = template.split(/{{(?:preview|three|card)}}/);
assert.equal(parts.length, 4);
fs.writeFileSync(
  "src/PlayerTemplate.sol",
  "// SPDX-License-Identifier: MIT\npragma solidity ^0.8.24;\n// Generated by tools/card/build.mjs from media/player.html.\nlibrary PlayerTemplate {\n" +
    parts
      .map(
        (s, i) =>
          "  string internal constant PART" +
          i +
          " = " +
          JSON.stringify(encodeURIComponent(s)) +
          ";",
      )
      .join("\n") +
    "\n}\n",
);
const preview = fs.existsSync("media/dist/front.webp")
  ? read("media/dist/front.webp")
  : Buffer.alloc(0);
fs.writeFileSync(
  "media/dist/inspect.html",
  parts[0] +
    preview.toString("base64") +
    parts[1] +
    three +
    parts[2] +
    card +
    parts[3],
);
const assets = [
  ["three", "three-v0.162.0-module.min.js.Base64.gz", three],
  ["card", "iif-card", card],
  ["preview", "iif-preview", preview],
].map(([role, name, bytes]) => ({
  role,
  filename:
    role === "three"
      ? name
      : name +
        "-" +
        keccak256(bytes).slice(2, 18) +
        (role === "preview" ? ".webp" : ".txt"),
  size: bytes.length,
  hash: keccak256(bytes),
}));
fs.writeFileSync(
  "media/dist/assets.json",
  JSON.stringify(assets, null, 2) + "\n",
);
execFileSync("forge", ["fmt", "src/PlayerTemplate.sol"]);
